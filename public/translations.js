window.toggleLang = function() {
    let lang = localStorage.getItem('krishi_mitra_lang') || localStorage.getItem('lang') || 'en';
    let newLang = lang === 'hi' ? 'en' : 'hi';
    localStorage.setItem('krishi_mitra_lang', newLang);
    localStorage.setItem('lang', newLang);
    
    // Live update translations without full page reload
    applyTranslations();
    
    // Call specific page loaders if they exist
    if (typeof loadDashboard === 'function') loadDashboard();
    if (typeof loadPrices === 'function') loadPrices();
    if (typeof loadNotifications === 'function') loadNotifications();
    if (typeof loadArticles === 'function') loadArticles();
    if (typeof loadCrops === 'function') loadCrops();
    if (typeof loadReminders === 'function') loadReminders();
    if (typeof loadCropDetail === 'function') loadCropDetail();
    if (typeof loadPests === 'function') loadPests();
    if (typeof loadProfileFields === 'function') loadProfileFields();
    if (typeof loadQueries === 'function') loadQueries();
    if (typeof loadHistory === 'function') loadHistory();
    if (typeof loadAdminInterface === 'function') loadAdminInterface();
    if (typeof loadLandingData === 'function') loadLandingData();
    if (typeof loadMandiDetail === 'function') loadMandiDetail();
    if (typeof displayWeather === 'function') {
        const cwd = JSON.parse(localStorage.getItem('weatherData'));
        if (cwd) displayWeather(cwd);
    }
    if (typeof populateSchemes === 'function' && typeof document.getElementById('schemesGrid') !== 'undefined') {
        const schemes = JSON.parse(localStorage.getItem('yojana_data')) || [];
        populateSchemes(schemes);
    }
    if (typeof window.loadDashboardOverview === 'function') window.loadDashboardOverview();
    if (typeof window.loadMandiManagement === 'function') window.loadMandiManagement();
    if (typeof window.loadUsersList === 'function') window.loadUsersList();
    if (typeof renderLandingPage === 'function') renderLandingPage();

    // Dispatch global event for anything else
    window.dispatchEvent(new Event('languageChanged'));
};

function changeLang(lang) {
    localStorage.setItem('lang', lang);
    localStorage.setItem('krishi_mitra_lang', lang);
    
    // Call the toggle-like live update logic seamlessly
    let current = localStorage.getItem('krishi_mitra_lang') || 'en';
    if(current !== lang) {
        window.toggleLang(); 
    } else {
        applyTranslations();
        window.dispatchEvent(new Event('languageChanged'));
    }
}

function setLanguage(lang) {
    changeLang(lang);
}

function loadLanguage() {
    let lang = localStorage.getItem("lang") || localStorage.getItem("krishi_mitra_lang") || "en";
    
    // Fallback support for new data-hi / data-en requested logic
    document.querySelectorAll("[data-hi]").forEach(el => {
        const text = (lang === "hi") ? el.getAttribute("data-hi") : el.getAttribute("data-en");
        if(text) el.innerText = text;
    });

    // Also update old UI if present
    const langBtn = document.getElementById('langToggleText');
    if (langBtn) {
        langBtn.innerText = lang === 'en' ? 'हिन्दी' : 'English';
    }
}

/**
 * Syncs legacy localStorage keys to current ones as requested.
 * Safe Data Recovery
 */
function syncLocalStorageData() {
    // Sync Language Key
    if (localStorage.getItem('lang') && !localStorage.getItem('krishi_mitra_lang')) {
        localStorage.setItem('krishi_mitra_lang', localStorage.getItem('lang'));
    } else if (localStorage.getItem('krishi_mitra_lang') && !localStorage.getItem('lang')) {
        localStorage.setItem('lang', localStorage.getItem('krishi_mitra_lang'));
    }

    // Recover Yojana Data
    let yojana = JSON.parse(localStorage.getItem("yojana_data")) 
               || JSON.parse(localStorage.getItem("yojanaData")) 
               || JSON.parse(localStorage.getItem("schemes_data")) 
               || [];
    localStorage.setItem("yojana_data", JSON.stringify(yojana));

    // Recover Crops Data
    let crops = JSON.parse(localStorage.getItem("crops_data")) 
              || JSON.parse(localStorage.getItem("cropsData")) 
              || JSON.parse(localStorage.getItem("admin_crops")) 
              || [];
    localStorage.setItem("crops_data", JSON.stringify(crops));
    
    // Recover Current Crops (Farmer added)
    let currentCrops = JSON.parse(localStorage.getItem("currentCrops")) || [];
    localStorage.setItem("currentCrops", JSON.stringify(currentCrops));

    // Recover Users
    let users = JSON.parse(localStorage.getItem("users")) || [];
    localStorage.setItem("users", JSON.stringify(users));

    // Recover Notifications / Alerts
    let notifications = JSON.parse(localStorage.getItem("notifications")) 
                      || JSON.parse(localStorage.getItem("alerts")) 
                      || [];
    localStorage.setItem("notifications", JSON.stringify(notifications));

    // Recover Support Messages
    let support_messages = JSON.parse(localStorage.getItem("support_messages")) || [];
    localStorage.setItem("support_messages", JSON.stringify(support_messages));
    
    // Queries
    let queries = JSON.parse(localStorage.getItem("queries")) || [];
    localStorage.setItem("queries", JSON.stringify(queries));

    console.log("Data Recovery Completed");
}

