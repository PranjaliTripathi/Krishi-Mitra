function applyTranslations() {
    loadLanguage();
    const lang = localStorage.getItem('krishi_mitra_lang') || localStorage.getItem('lang') || 'en';
    const t = translations[lang];
    if (!t) return;

    document.querySelectorAll('[data-t]').forEach(el => {
        const key = el.getAttribute('data-t');
        if (t[key]) {
            if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
                el.value = t[key];
            } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else {
                el.innerHTML = t[key];
            }
        }
    });

    // Update language toggle button text if exists
    const langBtn = document.getElementById('langToggleText');
    if (langBtn) {
        langBtn.innerText = lang === 'en' ? 'हिंदी' : 'English';
    }
}

// Global Initialization
document.addEventListener('DOMContentLoaded', function() {
    syncLocalStorageData();
    applyTranslations();
    
    // Sidebar robustness - fix links and ensure active state
    const sidebarLinks = document.querySelectorAll('.sidebar a, .admin-sidebar a');
    const currentPath = window.location.pathname.split('/').pop();
    
    sidebarLinks.forEach(link => {
        const href = link.getAttribute('href');
        if (href && href !== '#' && currentPath === href) {
            link.classList.add('active');
        }
    });

// Removed duplicate sidebar handling in applyTranslations as it interferes with page-specific logic.
});
